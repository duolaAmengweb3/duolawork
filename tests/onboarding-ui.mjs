import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {chromium} from 'playwright-core';
import {startHarness} from './v1-harness.mjs';

const outbound=[];
const h=await startHarness({outboundService:async request=>{
  const u=new URL(request.url);
  assert.equal(u.hostname,'api2.cursor.sh');
  assert.equal(u.pathname,'/automations/webhook/isolated-ui-fixture');
  const token=request.headers.get('Authorization');
  outbound.push({accepted:token==='Bearer crsr_correct_isolated_fixture'});
  return new Response(null,{status:token==='Bearer crsr_correct_isolated_fixture'?200:401});
}});
process.env.AGENT_HUB_DATA_DIR=path.join(h.directory,'local');
const {start}=await import('../local/server.mjs');
let local,browser; const checks=[],errors=[];
try {
  await h.request('/admin/action',{type:'settings.update',payload:{automation:false}});
  local=await start({port:0,maintenance:true,vaultKey:Buffer.alloc(32,17),config:{endpoint:h.base,adminKey:h.key,runnerId:'isolated-onboarding-ui'}});
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(local.url);
  await page.getByRole('button',{name:/成员与连接/}).click();
  await page.getByRole('button',{name:'添加成员',exact:true}).click();
  await page.getByRole('textbox',{name:'成员备注名称',exact:true}).fill('全新接入测试');
  await page.getByRole('combobox',{name:'成员平台',exact:true}).selectOption('grok-bot');
  await page.getByRole('button',{name:'保存成员',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByText('把 全新接入测试 加入团队',{exact:true}).waitFor();
  await dialog.getByRole('button',{name:'复制接入 Skill',exact:true}).click();
  await dialog.getByText('查看接入 Skill（也可手动复制）',{exact:true}).click();
  const skill=await dialog.getByRole('textbox',{name:'接入 Skill',exact:true}).inputValue();
  const code=skill.match(/配对码：([A-F0-9]{12})/)[1];
  const grant=await h.request('/v2/connect/redeem',{code,attemptId:'isolated-fresh-agent'},'');
  const memberId=grant.memberId;
  const tool=async(name,args={})=>{
    const r=await h.request('/v2/mcp',{jsonrpc:'2.0',id:1,method:'tools/call',params:{name,arguments:args}},grant.access_token);
    if(r.result.isError)throw new Error(JSON.stringify(r.result));
    return JSON.parse(r.result.content[0].text);
  };
  await h.request('/v2/self/status',{stage:'waiting_owner',action:'grok_routine',routineName:'Agent Hub 成员 全新接入测试 接收器',message:'接收器已就绪，请在 Hub 确认一次。'},grant.access_token);
  await dialog.getByText('还差一次 Grok 确认',{exact:true}).waitFor({timeout:20000});
  await dialog.getByRole('textbox',{name:'Grok 接收器地址',exact:true}).waitFor();
  await dialog.getByText(/再点击其中名为/).waitFor();
  await dialog.getByText(/POST 到/).waitFor();
  await dialog.getByText(/第三行「标头」不需要/).waitFor();
  assert.equal(await dialog.getByRole('button',{name:'进入高级接入',exact:true}).isVisible(),false);
  await fs.mkdir('evidence/screenshots',{recursive:true});
  await page.screenshot({path:'evidence/screenshots/onboarding-first-confirmation.png',fullPage:true});
  checks.push('界面新增成员后直接进入默认接入，Skill兑换和本人确认无需高级表单');
  await dialog.getByRole('textbox',{name:'Grok 接收器地址',exact:true}).fill('https://grok.com/bot/fixture');
  await dialog.getByRole('textbox',{name:'Grok 接收器密钥',exact:true}).fill('crsr_wrong_isolated_fixture');
  await dialog.getByRole('button',{name:'保存并自动验证',exact:true}).click();
  await dialog.getByText('请复制 Grok Bot 桌面例程里的 Webhook URL，不是聊天页或账号自动化地址。',{exact:true}).waitFor();
  assert.equal(outbound.length,0);
  await dialog.getByRole('textbox',{name:'Grok 接收器地址',exact:true}).fill('https://api2.cursor.sh/automations/webhook/isolated-ui-fixture');
  await dialog.getByRole('button',{name:'保存并自动验证',exact:true}).click();
  await dialog.getByText('尚未接通',{exact:true}).waitFor({timeout:25000});
  await dialog.getByText(/原平台返回 HTTP 401/).waitFor();
  assert.equal((await h.request('/v2/workspace')).connections.find(c=>c.id===memberId).status,'configured');
  checks.push('聊天页地址先被拦截，错误密钥真实模拟401后显示原因并能直接修正');
  await dialog.getByRole('textbox',{name:'Grok 接收器地址',exact:true}).fill('https://api2.cursor.sh/automations/webhook/isolated-ui-fixture');
  await dialog.getByRole('textbox',{name:'Grok 接收器密钥',exact:true}).fill('crsr_correct_isolated_fixture');
  await dialog.getByRole('button',{name:'修正并自动验证',exact:true}).click();
  await dialog.getByText('正在等待原 Agent 回复',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('button',{name:'查看接入',exact:true}).click();
  await page.getByRole('dialog').getByText('正在等待原 Agent 回复',{exact:true}).waitFor();
  assert.equal((await h.request('/v2/workspace')).connections.find(c=>c.id===memberId).status,'configured');
  checks.push('保存自动发起验证，HTTP200不冒充已回复，刷新后保留原验证而不重新配置');
  const work=(await tool('list_work')).work.find(w=>w.runId);
  const claim=await tool('claim_work',{requestId:'fresh-probe-claim',stepId:work.stepId});
  await tool('submit_work',{requestId:'fresh-probe-submit',attemptId:claim.attemptId,lease:claim.lease,items:[{title:'隔离协议往返',body:claim.input.instruction.match(/proof_[a-z0-9]+/)[0]}]});
  await page.getByRole('dialog').getByText('已接入，可以开始聊天',{exact:true}).waitFor({timeout:20000});
  assert.equal(await page.getByRole('textbox',{name:'Grok 接收器密钥',exact:true}).count(),0);
  const stored=await page.evaluate(()=>JSON.stringify({local:{...localStorage},session:{...sessionStorage}}));
  for(const secret of [grant.access_token,grant.refresh_token,'crsr_correct_isolated_fixture','crsr_wrong_isolated_fixture'])assert(!stored.includes(secret));
  await page.screenshot({path:'evidence/screenshots/onboarding-verified.png',fullPage:true});
  checks.push('只有成员自己的正确回传才能点亮接入；密钥不进入浏览器持久存储，成功后不再重复要求填写');
  await page.getByRole('button',{name:'开始聊天',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.getByText('单聊 · 只有你和这位 Agent',{exact:true}).waitFor();
  let dm=(await h.request('/v2/channels')).items.find(c=>c.direct);
  assert.deepEqual(dm.memberIds,[memberId]);
  assert.equal(await page.getByRole('button',{name:'管理群成员',exact:true}).count(),0);
  await page.getByRole('textbox',{name:'群消息',exact:true}).fill('单聊的真实协议消息');
  await page.getByRole('button',{name:'发送消息',exact:true}).click();
  const received=await tool('receive_messages',{requestId:'private-first-message'});
  assert.equal(received.input.channelId,dm.id);
  await page.getByRole('button',{name:/成员与连接/}).click();
  await page.getByRole('button',{name:'解除连接 全新接入测试',exact:true}).click();
  await page.getByRole('button',{name:'确认解除连接',exact:true}).click();
  await page.getByRole('dialog').getByRole('alert').getByText(/此成员正在回复/).waitFor();
  assert.equal((await h.request('/v2/workspace')).connections.find(c=>c.id===memberId).status,'verified');
  await page.getByRole('button',{name:'取消',exact:true}).click();
  await tool('post_message',{requestId:'private-first-reply',channelId:dm.id,turnId:received.turnId,body:'这是单聊回复'});
  await page.getByRole('button',{name:'聊天 全新接入测试',exact:true}).click();
  await page.getByRole('main').getByText('这是单聊回复',{exact:true}).waitFor({timeout:20000});
  assert.equal((await h.request('/v2/channels')).items.filter(c=>c.direct).length,1);
  await page.screenshot({path:'evidence/screenshots/member-direct-chat.png',fullPage:true});
  checks.push('接入成功按钮和成员卡片聊天都打开同一份独立单聊，正常消息能回传，不要求先建群');
  await page.getByRole('button',{name:/成员与连接/}).click();
  await page.getByRole('button',{name:'解除连接 全新接入测试',exact:true}).click();
  await page.getByRole('button',{name:'确认解除连接',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  assert.equal(await page.getByRole('button',{name:'聊天 全新接入测试',exact:true}).count(),0);
  const removed=await h.request('/v2/workspace');
  assert.equal(removed.members.length,0);
  assert.equal(removed.formerMembers.find(m=>m.id===memberId).name,'全新接入测试');
  assert.equal((await h.request('/v2/channel?id='+dm.id)).messages.length,2);
  await assert.rejects(()=>tool('list_work'));
  checks.push('解除连接要确认；执行中拒绝且不半撤销，空闲时撤销旧令牌并移出列表，聊天与账号保留');
  assert.deepEqual(errors,[]);
  const evidence={at:new Date().toISOString(),checks,fixtureOnly:true,realCommercialAgentTested:false,unexpectedOutboundRequests:0,providerResponses:outbound.map(x=>x.accepted?200:401)};
  await fs.writeFile('evidence/onboarding-ui.json',JSON.stringify(evidence,null,2)+'\n');
  console.log(JSON.stringify(evidence,null,2));
}catch(e){if(browser?.contexts()[0]?.pages()[0])await browser.contexts()[0].pages()[0].screenshot({path:'/tmp/hub-onboarding-ui-failure.png',fullPage:true});throw e;}
finally{await browser?.close();await local?.close();await h.stop();}
