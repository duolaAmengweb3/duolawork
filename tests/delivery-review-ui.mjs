import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {chromium} from 'playwright-core';
import {startHarness} from './v1-harness.mjs';
import {Repository} from '../cloud/collaboration/repository.mjs';
import {conversationMaintenance} from '../cloud/collaboration/conversation.mjs';
const h=await startHarness();let local,browser;const checks=[],errors=[];
try{
 await h.request('/admin/action',{type:'settings.update',payload:{automation:false}});
 const coordinator=await h.member('grok-bot','负责人'),a=await h.member('grok-bot','写作者'),b=await h.member('grok-bot','审阅者');
 const group=await h.command('channel.create',{name:'消息异常处理验收',memberIds:[coordinator.id,a.id,b.id],coordinatorId:coordinator.id});
 const message=await h.command('channel.post',{channelId:group.id,body:'请完成白皮书章节互审，交付修改后的正文。',mentions:[a.id,b.id]});
 const repo=new Repository(h.db,'v1-test');
 await repo.transact('ui-historical-hold',{},async tx=>{for(const t of await tx.list('channel_turn',{scope:group.id}))tx.put('channel_turn',{...t,status:'limited',reason:'旧的次数限制'});});
 const state=await h.request('/admin/state'),identity={members:state.members,accounts:state.accounts};
 await conversationMaintenance(repo,identity);
 process.env.AGENT_HUB_DATA_DIR=path.join(h.directory,'local');const {start}=await import('../local/server.mjs');
 local=await start({port:0,maintenance:true,vaultKey:Buffer.alloc(32,25),config:{endpoint:h.base,adminKey:h.key,runnerId:'delivery-review-ui'}});
 browser=await chromium.launch({channel:'chrome',headless:true});const page=await browser.newPage({viewport:{width:1440,height:960}});page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(id=>localStorage.setItem('hub-communication',JSON.stringify({channelId:id,chatKind:'group',spaceTab:'activity'})),group.id);
 await page.goto(local.url);await page.getByRole('heading',{name:'消息异常处理验收',exact:true}).waitFor();
 await page.getByRole('button',{name:/正在核对 1 件消息异常/}).click();
 await page.getByText('暂时没有需要你操作的事情',{exact:true}).waitFor();
 assert.equal(await page.locator('.delivery-auto .delivery-case').count(),1);assert.equal(await page.getByText('连续回应已暂停',{exact:true}).count(),0);
 assert.ok((await page.locator('.delivery-case').first().innerText()).includes('白皮书章节互审'));checks.push('同一消息两位成员合为一件，显示原需求，不计入人类待办');
 await page.screenshot({path:'evidence/delivery-review-auto.png'});
 const issue=(await repo.list('channel_delivery_issue',{scope:group.id}))[0];
 await coordinator.call('resolve_delivery',{requestId:'ui-decision',channelId:group.id,issueId:issue.id,expectedVersion:issue.version,action:'needs_user',summary:'白皮书需要确定面向技术读者还是业务读者，影响章节表达。',nextAction:'请告诉负责人优先面向哪类读者，已有草稿保留。'});
 await page.getByText('请告诉负责人优先面向哪类读者，已有草稿保留。',{exact:true}).waitFor();
 assert.equal(await page.locator('.delivery-case.attention').count(),1);checks.push('真正的决策显示影响、具体问题和沟通入口');
 await page.getByRole('textbox',{name:'群消息'}).fill('已有草稿不能被覆盖');
 await page.getByRole('button',{name:'和负责人沟通',exact:true}).click();
 assert.equal(await page.getByRole('textbox',{name:'群消息'}).inputValue(),'已有草稿不能被覆盖');checks.push('沟通入口保留用户草稿，引用原消息并指向负责人');
 await page.screenshot({path:'evidence/delivery-review-attention.png'});
 await page.setViewportSize({width:900,height:820});assert.ok(await page.locator('.delivery-case.attention').isVisible());
 assert.ok(await page.locator('.delivery-list').evaluate(el=>el.scrollWidth<=el.clientWidth+1));await page.screenshot({path:'evidence/delivery-review-narrow.png'});checks.push('窄窗口卡片与操作无横向溢出');
 await page.getByRole('button',{name:'不再需要',exact:true}).click();await page.getByText('暂时没有需要你操作的事情',{exact:true}).waitFor();
 const closed=await repo.get('channel_delivery_issue',issue.id);assert.equal(closed.status,'resolved');
 assert.equal((await repo.list('channel_turn',{scope:group.id})).filter(t=>!t.deliveryReview&&t.status==='ready').length,0);checks.push('用户明确不再需要后收进历史，不重发旧任务');
 assert.deepEqual(errors,[]);await fs.writeFile('evidence/delivery-review-ui.json',JSON.stringify({at:new Date().toISOString(),scope:'isolated UI and HTTP; not native Agent execution',checks,errors},null,2));console.log(JSON.stringify({checks}));
}finally{await browser?.close();await local?.close();await h.stop();}
