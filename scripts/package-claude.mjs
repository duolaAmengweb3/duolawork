import {build} from 'esbuild';
import fs from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
const result=await build({entryPoints:['connectors/claude/cli.mjs'],bundle:true,platform:'node',format:'cjs',target:'node22',write:false,minify:true,legalComments:'inline'});
const bytes=result.outputFiles[0].contents,sha256=createHash('sha256').update(bytes).digest('hex'),compressed=gzipSync(bytes);
await fs.writeFile('cloud/collaboration/claude-download.mjs',`// Generated by scripts/package-claude.mjs; no credentials or user data.\nexport const sha256=${JSON.stringify(sha256)};\nexport const compressed=${JSON.stringify(compressed.toString('base64'))};\n`);
await fs.mkdir('release/claude',{recursive:true});await fs.writeFile('release/claude/connector.cjs',bytes);
console.log(JSON.stringify({sha256,bytes:bytes.length,gzip:compressed.length}));
