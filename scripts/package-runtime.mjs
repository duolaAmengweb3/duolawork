import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const stage=path.resolve('release/native-runtime'),archive=path.resolve('release/native-runtime.tgz');
await fs.rm(stage,{recursive:true,force:true});
await fs.mkdir(stage,{recursive:true});
for(const name of ['local','shared','connectors/runtime'])await fs.cp(name,path.join(stage,name),{recursive:true});
const sourceHash=createHash('sha256');
for(const name of (await fs.readdir(stage,{recursive:true})).sort()){
 const file=path.join(stage,name);if(name==='shared/build-info.json'||!(await fs.stat(file)).isFile())continue;
 sourceHash.update(name);sourceHash.update(await fs.readFile(file));
}
const revision=sourceHash.digest('hex');
await fs.writeFile(path.join(stage,'runtime-version.json'),JSON.stringify({revision}));
await fs.writeFile(path.join(stage,'package.json'),JSON.stringify({name:'duolawork-native-runtime',type:'module',version:'1.0.0',private:true}));
for(const name of ['undici','ws','yaml'])await fs.cp(path.join('node_modules',name),path.join(stage,'node_modules',name),{recursive:true});
execFileSync('tar',[...(process.platform==='darwin'?['--no-xattrs']:[]),'-czf',archive,'-C',stage,'package.json','runtime-version.json','local','shared','connectors','node_modules'],{env:{...process.env,COPYFILE_DISABLE:'1'}});
const bytes=await fs.readFile(archive),sha256=createHash('sha256').update(bytes).digest('hex');
await fs.writeFile('cloud/collaboration/runtime-download.mjs',`// Generated by scripts/package-runtime.mjs. Public program files only.\nexport const revision=${JSON.stringify(revision)};\nexport const sha256=${JSON.stringify(sha256)};\nexport const archive=${JSON.stringify(bytes.toString('base64'))};\n`);
console.log(JSON.stringify({sha256,bytes:bytes.length}));
